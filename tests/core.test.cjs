const test = require('node:test');
const assert = require('node:assert/strict');
const core = require('../app.js');
const make=(extra={})=>({id:'x1',title:'Estudar JavaScript',description:'Funções',priority:'media',status:'todo',due:'2026-11-05',category:'Estudos',...extra});
test('normaliza tarefa válida',()=>assert.equal(core.normalizeTask(make()).title,'Estudar JavaScript'));
test('rejeita título vazio',()=>assert.equal(core.normalizeTask(make({title:' '})),null));
test('rejeita status inválido',()=>assert.equal(core.normalizeTask(make({status:'paused'})),null));
test('rejeita prioridade inválida',()=>assert.equal(core.normalizeTask(make({priority:'ultra'})),null));
test('migra prioridades da versão anterior',()=>assert.equal(core.normalizeTask(make({priority:'Média'})).priority,'media'));
test('escapa HTML de usuário',()=>assert.equal(core.escapeHtml('<script>"'),'&lt;script&gt;&quot;'));
test('data local recebe ano mês dia',()=>assert.equal(core.localToday(new Date(2026,10,5)),'2026-11-05'));
test('valida dia inexistente',()=>assert.equal(core.validDate('2026-02-31'),false));
test('restaura backup com estrutura v2',()=>assert.equal(core.normalizeBackup({tasks:[make()]}).length,1));
test('restaura backup de array',()=>assert.equal(core.normalizeBackup([make()]).length,1));
test('rejeita arquivo inválido',()=>assert.throws(()=>core.normalizeBackup({foo:1}),/inválido/));
test('busca em categoria',()=>assert.equal(core.filterTasks([make()],{search:'ESTUDOS'}).length,1));
test('filtra por prioridade',()=>assert.equal(core.filterTasks([make()],{priority:'alta'}).length,0));
test('filtra atrasadas abertas',()=>assert.equal(core.filterTasks([make()],{today:'2026-11-06',due:'overdue'}).length,1));
test('não conta concluídas como atrasadas',()=>assert.equal(core.filterTasks([make({status:'done'})],{today:'2026-11-06',due:'overdue'}).length,0));
test('filtra sem prazo',()=>assert.equal(core.filterTasks([make({due:''})],{due:'nodate'}).length,1));
test('calcula métricas e percentual',()=>assert.deepEqual(core.stats([make(),make({id:'x2',status:'done'})],'2026-11-06'),{total:2,done:1,doing:0,overdue:1,rate:50}));
test('não divide por zero',()=>assert.equal(core.stats([]).rate,0));
